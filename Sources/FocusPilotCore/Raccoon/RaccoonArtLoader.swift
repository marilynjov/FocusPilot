import CoreGraphics
import Foundation
import ImageIO

public enum RaccoonArtError: Error, Equatable, CustomStringConvertible {
    case missingManifest(String)
    case unreadableManifest(String)
    case unknownPose(String)
    case unreadableStrip(String)
    /// The strip is not `frameSize` high and `frameSize` × layers wide.
    case wrongStripSize(String)

    public var description: String {
        switch self {
        case .missingManifest(let path): "The raccoon art is missing: \(path)"
        case .unreadableManifest(let why): "The raccoon art description can’t be read: \(why)"
        case .unknownPose(let id): "The raccoon has no pose named \(id)"
        case .unreadableStrip(let name): "The raccoon picture \(name) can’t be read"
        case .wrongStripSize(let name): "The raccoon picture \(name) has the wrong size"
        }
    }
}

/// The raccoon art as the app uses it at run time: the manifest from the
/// bundled `Raccoon` folder, and each pose's strip cut into one image per
/// layer. Only reads; the art is generated by `scripts/build-raccoon-art.sh`.
public struct RaccoonArt: Sendable {
    /// The folder `scripts/build-app.sh` copies `Packaging/Raccoon` into.
    public static let bundleFolder = "Raccoon"

    public let manifest: RaccoonArtManifest
    public let directory: URL

    public init(manifest: RaccoonArtManifest, directory: URL) {
        self.manifest = manifest
        self.directory = directory
    }

    /// Reads `raccoon.json` from `directory`.
    public static func load(from directory: URL) throws -> RaccoonArt {
        let url = directory.appending(path: RaccoonArtManifest.fileName)
        guard let data = try? Data(contentsOf: url) else { throw RaccoonArtError.missingManifest(url.path) }
        do {
            return RaccoonArt(manifest: try JSONDecoder().decode(RaccoonArtManifest.self, from: data), directory: directory)
        } catch {
            throw RaccoonArtError.unreadableManifest(String(describing: error))
        }
    }

    /// The art in `bundle`'s `Contents/Resources/Raccoon`.
    public static func bundled(in bundle: Bundle = .main) throws -> RaccoonArt {
        guard let resources = bundle.resourceURL else {
            throw RaccoonArtError.missingManifest("\(bundle.bundlePath)/Contents/Resources/\(bundleFolder)")
        }
        return try load(from: resources.appending(path: bundleFolder))
    }

    /// The pose's layers, each a `frameSize` square cut from its strip.
    public func layers(of poseID: String) throws -> [RaccoonLayer: CGImage] {
        guard let pose = manifest.pose(poseID) else { throw RaccoonArtError.unknownPose(poseID) }
        let url = directory.appending(path: pose.image)
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let strip = CGImageSourceCreateImageAtIndex(source, 0, [kCGImageSourceShouldCache: true] as CFDictionary)
        else { throw RaccoonArtError.unreadableStrip(pose.image) }
        return try Self.slice(strip, layers: pose.layers, frameSize: manifest.frameSize, name: pose.image)
    }

    /// Cuts a strip into its layers, left to right in `layers` order.
    public static func slice(_ strip: CGImage, layers: [RaccoonLayer], frameSize: Int,
                             name: String = "strip") throws -> [RaccoonLayer: CGImage] {
        guard strip.height == frameSize, strip.width == frameSize * layers.count else {
            throw RaccoonArtError.wrongStripSize(name)
        }
        var images: [RaccoonLayer: CGImage] = [:]
        for (index, layer) in layers.enumerated() {
            let rect = CGRect(x: index * frameSize, y: 0, width: frameSize, height: frameSize)
            guard let image = strip.cropping(to: rect) else { throw RaccoonArtError.unreadableStrip(name) }
            images[layer] = image
        }
        return images
    }
}

// MARK: - Motion as animation tracks

/// One animatable property of a motion keyframe.
public enum RaccoonMotionProperty: String, CaseIterable, Sendable {
    case translateX, translateY, rotate, scaleX, scaleY, opacity

    /// The value when no keyframe sets it (CSS: the element's own value).
    public var restValue: Double {
        switch self {
        case .translateX, .translateY, .rotate: 0
        case .scaleX, .scaleY, .opacity: 1
        }
    }

    func value(in keyframe: RaccoonKeyframe) -> Double? {
        switch self {
        case .translateX: keyframe.translateX
        case .translateY: keyframe.translateY
        case .rotate: keyframe.rotate
        case .scaleX: keyframe.scaleX
        case .scaleY: keyframe.scaleY
        case .opacity: keyframe.opacity
        }
    }
}

/// One property's values over a cycle, ready for a keyframe animation:
/// `keyTimes` ascend from 0 to 1, one value each.
public struct RaccoonMotionTrack: Equatable, Sendable {
    public var property: RaccoonMotionProperty
    public var keyTimes: [Double]
    public var values: [Double]

    public init(property: RaccoonMotionProperty, keyTimes: [Double], values: [Double]) {
        self.property = property
        self.keyTimes = keyTimes
        self.values = values
    }
}

extension RaccoonMotion {
    /// One track per property the motion sets, with CSS keyframe semantics:
    /// a property is interpolated only between the keyframes that set it,
    /// and takes its rest value at 0 or 1 when no keyframe sets it there.
    public var tracks: [RaccoonMotionTrack] {
        let points = keyframes.flatMap { keyframe in keyframe.at.map { ($0, keyframe) } }
            .sorted { $0.0 < $1.0 }
        return RaccoonMotionProperty.allCases.compactMap { property in
            var times: [Double] = [], values: [Double] = []
            for (time, keyframe) in points {
                guard let value = property.value(in: keyframe) else { continue }
                if let last = times.last, last == time {
                    values[values.count - 1] = value
                } else {
                    times.append(time)
                    values.append(value)
                }
            }
            guard !times.isEmpty else { return nil }
            if times.first! > 0 {
                times.insert(0, at: 0)
                values.insert(property.restValue, at: 0)
            }
            if times.last! < 1 {
                times.append(1)
                values.append(property.restValue)
            }
            return RaccoonMotionTrack(property: property, keyTimes: times, values: values)
        }
    }
}

// MARK: - Presence

/// Where the raccoon companion appears (decision 0004, proposed modes).
/// Stored in `DisplayPreferences`; a new install starts with `off` until
/// the owner confirms a default.
public enum RaccoonCompanionMode: String, CaseIterable, Identifiable, Sendable {
    /// In the planning window while a task runs, and on the chosen display
    /// while a task runs with the window closed.
    case staysOnScreen
    /// Hidden until a reminder brings it in (D12).
    case peeksForReminders
    case off

    public static let `default` = RaccoonCompanionMode.off

    public var id: String { rawValue }

    public var title: String {
        switch self {
        case .staysOnScreen: "On screen while a task runs"
        case .peeksForReminders: "Peeks in for reminders only"
        case .off: "Off"
        }
    }
}

/// A button under the raccoon's speech bubble (D12). Each runs the same
/// app command as the menu bar and focus panel; none has logic of its own.
public enum RaccoonPeekAction: Hashable, Sendable {
    /// Dismisses the peek.
    case gotIt
    /// Adds time to the session under way.
    case extend(minutes: Int)
    /// Starts a new session on the same task once one has ended.
    case keepGoing(minutes: Int)
    /// Takes a break the owner chose, which stops the countdown.
    case takeBreak(minutes: Int)
    /// Ends the break.
    case backToTask
    /// Dismisses the peek after a session ended.
    case done

    public var title: String {
        switch self {
        case .gotIt: "Got it"
        case .extend(let minutes): "+\(minutes) min"
        case .keepGoing(let minutes): "Keep going +\(minutes) min"
        case .takeBreak(let minutes): "Break \(minutes) min"
        case .backToTask: "Back to task"
        case .done: "Done"
        }
    }
}

/// A reminder that brings the raccoon in for a moment: which pose to show
/// and, optionally, what its speech bubble says and the buttons under it.
public struct RaccoonPeek: Equatable, Sendable {
    public var poseID: String
    public var message: String?
    public var actions: [RaccoonPeekAction]

    public init(poseID: String, message: String? = nil, actions: [RaccoonPeekAction] = []) {
        self.poseID = poseID
        self.message = message
        self.actions = actions
    }
}

/// What the owner's task is doing, as far as the raccoon cares.
public enum RaccoonActivity: Equatable, Sendable {
    case working
    case paused
    case onBreak
    /// On a break that is the plan's lunch (owner request, 2026-11-02).
    case onLunch

    /// Nil when no session is under way. `isLunch` comes from the plan
    /// (`RaccoonMoments.isOnLunch`).
    public init?(_ phase: SessionPhase?, isLunch: Bool = false) {
        switch phase {
        case .running: self = .working
        case .paused: self = .paused
        case .onBreak: self = isLunch ? .onLunch : .onBreak
        case .ended, nil: return nil
        }
    }

    /// Working at the laptop, sitting while paused, coffee on a break, a
    /// nap at lunch.
    public var poseID: String {
        switch self {
        case .working: RaccoonPresence.workingPose
        case .paused: RaccoonPresence.idlePose
        case .onBreak: RaccoonPresence.breakPose
        case .onLunch: RaccoonPresence.lunchPose
        }
    }
}

/// What the companion window shows: a pose and an optional bubble, or
/// nothing. Pure, so the choice is testable without a window.
public struct RaccoonPresence: Equatable, Sendable {
    public static let idlePose = "sit"
    public static let workingPose = "laptop"
    public static let breakPose = "coffee"
    public static let lunchPose = "sleep"

    public var poseID: String
    public var message: String?

    public init(poseID: String, message: String? = nil) {
        self.poseID = poseID
        self.message = message
    }

    /// The floating window: the task's pose while a session is under way
    /// and the planning window is closed (the window shows it instead); a
    /// peek replaces that while it lasts. Peeks-in mode shows only peeks.
    public static func resolve(mode: RaccoonCompanionMode, activity: RaccoonActivity?, isWindowOpen: Bool,
                               peek: RaccoonPeek?) -> RaccoonPresence? {
        switch mode {
        case .off:
            return nil
        case .peeksForReminders:
            return peek.map { RaccoonPresence(poseID: $0.poseID, message: $0.message) }
        case .staysOnScreen:
            if let peek { return RaccoonPresence(poseID: peek.poseID, message: peek.message) }
            guard let activity, !isWindowOpen else { return nil }
            return RaccoonPresence(poseID: activity.poseID)
        }
    }

    /// The planning window, in On screen mode: the task's pose while a
    /// session is under way. Hidden during a peek, which the floating
    /// window shows, so there is only ever one raccoon.
    public static func inWindow(mode: RaccoonCompanionMode, activity: RaccoonActivity?,
                                peek: RaccoonPeek? = nil) -> RaccoonPresence? {
        guard mode == .staysOnScreen, peek == nil, let activity else { return nil }
        return RaccoonPresence(poseID: activity.poseID)
    }
}
